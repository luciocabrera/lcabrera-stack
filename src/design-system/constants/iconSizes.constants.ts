/**
 * Centralized icon size tokens (in pixels).
 * These map to the `size` prop accepted by all Icon components.
 */

/** 12px – compact contexts (e.g. Tag close icon) */
export const ICON_SIZE_XS = 12;

/** 14px – dense UI elements (e.g. header sort indicators, header menu) */
export const ICON_SIZE_SM = 14;

/** 16px – standard action icons (e.g. drawer/toolbar buttons, list icons) */
export const ICON_SIZE_MD = 16;

/** 20px – prominent icons (e.g. side-panel titles, toolbar navigation) */
export const ICON_SIZE_LG = 20;
