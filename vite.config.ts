import { defineConfig } from 'vite-plus';

import { createFmtConfig } from '@lcabrera/vite-config/fmt';
import { createLintConfig } from '@lcabrera/vite-config/lint';

/**
 * Every workspace in this repo, classified by runtime.
 *
 * It lives here, not in `@lcabrera/vite-config`, because it is this repo's own
 * directory roster and no consumer's (ADR-069) — and here specifically because
 * the root config is already this repo's one lint-config home (ADR-042).
 * `vp run lint:plugins:verify` fails if a workspace is missing from all three
 * lists, or if a glob here names a workspace that no longer exists, and reads
 * this export to do it.
 *
 * `env` only supplies globals to the `no-undef` family, which is not enabled
 * today, so these are inert as rules and exact as documentation. They become
 * load-bearing the moment a category containing `no-undef` is turned on, which
 * is why they are kept correct rather than deleted.
 */
export const WORKSPACE_RUNTIMES = {
  /**
   * Neither runtime, and so neither set of globals. `@lcabrera/utils` guarantees
   * pure, side-effect-free helpers: its tsconfig gives it no DOM lib and no node
   * types, and anything that must touch the process belongs in `@lcabrera/node`
   * instead. Handing it `process` here would contradict the boundary the
   * tsconfig exists to enforce.
   */
  agnostic: ['packages/utils/**'],
  /** Workspaces whose code runs in a browser. */
  browser: [
    'apps/showcase/**',
    'packages/ui/**',
    // Browser-safe by construction — its tsconfig omits node types (ADR-038).
    'packages/api/**',
  ],
  /** Workspaces whose code runs in Node — services and build tooling alike. */
  node: [
    'packages/devkit/**',
    'packages/node-runtime/**',
    'packages/repo-standards/**',
    'packages/server/**',
    'packages/eslint-local-rules/**',
    'packages/ts-configs/**',
    'packages/tsconfig/**',
    'packages/vite-configs/**',
  ],
};

const fmtConfig = createFmtConfig({
  // `reports/sonar/` is machine-generated by `scripts/sonar-report.mjs` with
  // `JSON.stringify(…, null, 2)` — the same stable convention the other report
  // generators use. Sonar findings carry populated short arrays (e.g. issue
  // `tags`) that Oxfmt collapses onto one line, so the generator and formatter
  // would fight and churn the file on every run. Keep Oxfmt out of it; the
  // generator's output is the canonical, deterministic format.
  // `reports/pr-queue/` is the same case: `scripts/pr-queue-operator.mjs` writes
  // each pass's decision log with the same stable `JSON.stringify(…, null, 2)`
  // convention, and the markdown alongside it is generated too.
  ignorePatterns: [
    '.react-router/',
    'build/',
    'reports/pr-queue/',
    'reports/sonar/',
  ],
});

/** Exported so `scripts/verify-lint-plugins.mjs` can read the live plugin list. */
export const lintConfig = createLintConfig({
  workspaceRuntimes: WORKSPACE_RUNTIMES,
});

export default defineConfig({
  fmt: fmtConfig,
  // Vite+ reads `lint` from this file only; a workspace's own `lint` block is
  // never loaded. Per-workspace differences are `overrides` inside this config.
  lint: lintConfig,
  run: {
    tasks: {
      build: {
        // Orchestrator — individual package tasks handle their own caching
        cache: false,
        command: 'vp run -r build',
      },
    },
  },
  staged: {
    '*': 'vp check --fix',
    // `vp check` is fmt + Oxlint + tsgolint and knows nothing about Biome, so
    // without this entry the Biome gate would only ever fail in CI — after the
    // commit it was supposed to block. Check-only on purpose: unlike the
    // `--fix` above, a Biome autofix here could rewrite a staged file after it
    // was reviewed, so a violation fails the commit and `vp run lint:biome`
    // applies the fix deliberately.
    '*.{ts,tsx,mjs,cjs}': 'biome lint --no-errors-on-unmatched',
  },
});
